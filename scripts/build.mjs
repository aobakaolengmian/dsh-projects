/**
 * Build the browser module bundle: src/client/index.jsx -> client.js.
 *
 * The DSH web shell loads plugin bundles as
 *   window.__ModuleLoader__.load({ id, factory })   // factory returns exports
 * so the esbuild CommonJS output is wrapped in that factory. `react`,
 * `react-dom` and `react/jsx-runtime` are resolved by the shell's shared
 * module table and stay external.
 */
import { build } from 'esbuild'
import { readFile, writeFile } from 'node:fs/promises'
import { existsSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const cssFile = join(root, 'src/client/styles.css')
const css = existsSync(cssFile) ? await readFile(cssFile, 'utf8') : ''

const result = await build({
  entryPoints: [join(root, 'src/client/index.jsx')],
  bundle: true,
  format: 'cjs',
  platform: 'browser',
  target: ['chrome120'],
  external: ['react', 'react-dom', 'react/jsx-runtime'],
  define: { __PROJECTS_CSS__: JSON.stringify(css) },
  jsx: 'automatic',
  write: false,
  logLevel: 'warning',
  legalComments: 'none',
})

const body = result.outputFiles[0].text
const banner = `/* dsh-projects client bundle — generated by scripts/build.mjs; edit src/client/* and rebuild. */
window.__ModuleLoader__.load({
  id: '@wxysskd/dsh-projects',
  factory(require) {
    var module = { exports: {} };
    var exports = module.exports;
`
const footer = `    return module.exports;
  },
});
`
await writeFile(join(root, 'client.js'), banner + body + footer)
console.log(`client.js written (${(banner.length + body.length + footer.length) / 1024 | 0} KiB)`)
