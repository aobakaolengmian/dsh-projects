export const inject = ['slots', 'locale', 'sessions', 'workspaces', 'uiWorkspace']

export function apply(ctx) {
  ctx.effect(() => ctx.locale.register(NS, { zh, en }), 'dsh-projects: dictionaries')

  // One plugin-owned stylesheet; the shipped ui-workspace does the same for its
  // CSS module (the web shell gives slots no style seam).
  ctx.effect(() => {
    const tag = document.createElement('style')
    tag.dataset.plugin = '@local/dsh-projects'
    tag.textContent = CSS
    document.head.appendChild(tag)
    return () => {
      tag.remove()
    }
  }, 'dsh-projects: styles')

  const projectState = createProjectStateStore()
  const uiState = createUiStateStore()
  const actions = createActions(ctx, projectState, uiState)

  projectState.loadWithRetry().catch(() => {})

  ctx.slots.inject('sidebar.workspaces', () =>
    ctx.slots.register(
      {
        name: 'sidebar.workspaces',
        priority: -1,
        locale: NS,
        inject: () => ({
          actions,
          hooks: {
            projectState: projectState.store,
            uiState: uiState.store,
          },
        }),
      },
      Browser,
    ),
  )
}
